const fs = require('fs');
const http = require('http');
const vm = require('vm');
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const source = fs.readFileSync(require('path').join(__dirname,'../notion-print/index.html'),'utf8');
const out = process.env.TEST_OUTPUT_DIR || fs.mkdtempSync(require('path').join(require('os').tmpdir(),'notion-print-test-'));
console.log('Test output:',out);
fs.mkdirSync(out,{recursive:true});
const results = {};
for (const m of source.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)) new vm.Script(m[1]);
results.syntax = 'PASS';
const server = http.createServer((req,res)=>{res.setHeader('Content-Type','text/html; charset=utf-8');res.end(source)});
(async()=>{
 await new Promise(r=>server.listen(0,'127.0.0.1',r));
 const browser = await chromium.launch({channel:'chrome',headless:true});
 try {
 const page = await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('dialog',d=>d.accept());
 await page.goto('http://127.0.0.1:'+server.address().port);
 results.initialStatus=await page.locator('#status').innerText();
 await page.locator('#editor').fill('지리 수업 테스트 자료\n학생 개인정보가 없는 가상 문서입니다.');
 await page.locator('#fontSize').fill('16'); await page.locator('#fontSize').press('Tab');
 await page.locator('#marginSize').fill('15'); await page.locator('#marginSize').press('Tab');
 results.controls=await page.evaluate(()=>({font:getComputedStyle(editor).fontSize,padding:getComputedStyle(document.querySelector('.paper')).padding}));
 await page.getByRole('button',{name:'저장',exact:true}).click();
 await page.locator('#editor').fill('임시 변경');
 await page.getByRole('button',{name:'불러오기',exact:true}).click();
 results.savedRestored=(await page.locator('#editor').innerText()).includes('지리 수업 테스트 자료');
 await page.locator('#editor').click(); await page.keyboard.press('Control+End');
 await page.getByRole('button',{name:'페이지 나눔',exact:true}).click();
 await page.locator('#editor').press('End'); await page.keyboard.type('Second page sample');
 results.breakBeforePaste=await page.locator('.page-break').count();
 results.breakStatus=await page.locator('#status').innerText();
 await page.pdf({path:out+'/print-page-break.pdf',preferCSSPageSize:true,printBackground:true});
 await page.screenshot({path:out+'/print-desktop.png',fullPage:true});
 // Exercise the actual paste cleanup handler without accessing the system clipboard.
 await page.locator('#editor').dispatchEvent('paste');
 await page.waitForTimeout(100);
 results.breakAfterPaste=await page.locator('.page-break').count();
 await page.locator('#imgMax').selectOption('50%');
 await page.getByRole('button',{name:'새 문서',exact:true}).click();
 results.newDocumentImage=await page.evaluate(()=>({control:document.querySelector('#imgMax').value,actual:getComputedStyle(document.documentElement).getPropertyValue('--img-max').trim()}));
 await page.locator('#editor').fill(Array.from({length:100},(_,i)=>`${i+1}. 지역 특성을 비교하는 가상 수업 문장입니다.`).join('\n'));
 results.beforeFit=await page.locator('#status').innerText();
 await page.getByRole('button',{name:'자동 맞춤',exact:true}).click();
 results.afterFit=await page.locator('#status').innerText();
 await page.pdf({path:out+'/print-autofit.pdf',preferCSSPageSize:true,printBackground:true});
 await page.setViewportSize({width:390,height:844});
 results.mobile=await page.evaluate(()=>({viewport:innerWidth,documentWidth:document.documentElement.scrollWidth,paperWidth:document.querySelector('.paper').getBoundingClientRect().width}));
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:out+'/print-mobile.png',fullPage:true});
 results.errors=errors;
 assert.equal(results.initialStatus,'예상 1쪽');
 assert.equal(results.breakStatus,'예상 2쪽');
 assert.equal(results.breakAfterPaste,1);
 assert.equal(results.newDocumentImage.control,results.newDocumentImage.actual);
 assert.equal(results.savedRestored,true);
 assert.equal(results.afterFit,'예상 1쪽');
 await page.evaluate(()=>{
   editor.innerHTML='<p>첫 페이지</p><div class="page-break" contenteditable="false"></div><p>둘째 페이지</p><div class="page-break" contenteditable="false"></div><p>셋째 페이지</p>';
   updatePages();
 });
 results.threePagesMobile=await page.locator('#status').innerText();
 assert.equal(results.threePagesMobile,'예상 3쪽');
 await page.setViewportSize({width:1440,height:1000});
 assert.equal(await page.locator('#status').innerText(),'예상 3쪽');
 await page.pdf({path:out+'/print-three-pages.pdf',preferCSSPageSize:true,printBackground:true});
 await page.locator('#imgMax').selectOption('50%');
 await page.getByRole('button',{name:'저장',exact:true}).click();
 await page.getByRole('button',{name:'새 문서',exact:true}).click();
 await page.getByRole('button',{name:'불러오기',exact:true}).click();
 assert.equal(await page.locator('#imgMax').inputValue(),'50%');
 assert.equal(await page.locator('.page-break').count(),2);
 assert.equal(await page.locator('#status').innerText(),'예상 3쪽');
 results.restoreImageAndBreaks='PASS';
 assert.deepEqual(errors,[]);
 fs.writeFileSync(out+'/test-results.json',JSON.stringify(results,null,2));
 console.log(JSON.stringify(results,null,2));
 } finally {await browser.close();server.close();}
})().catch(e=>{console.error(e);server.close();process.exitCode=1;});
